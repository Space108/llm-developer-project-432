-- Пустые умолчания из 0007 нужны только вставкам в форме каркаса, а они помечают строку kind.
-- Строка без kind (рабочий поток) обязана задать имя файла, статус и путь явно: пустое
-- умолчание не должно тихо попасть в рабочие данные, если код когда-нибудь забудет поле.
-- NOT VALID: правило действует для новых и изменяемых строк, старые не проверяются.
ALTER TABLE documents
    ADD CONSTRAINT documents_explicit_fields
    CHECK (kind <> '' OR (filename <> '' AND status <> '' AND path <> ''))
    NOT VALID;
